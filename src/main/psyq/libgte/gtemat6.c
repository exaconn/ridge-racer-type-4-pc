#include "types.h"
#include "rr/cpu_md_leaf.h"

int *ScaleMatrix(int *a0_in, int *a1) {
    int *a0 = a0_in;
    int t0;
    int t1;
    int t2;
    int t3;
    int t4;
    int t5;

    t3 = a1[0];
    t4 = a1[1];
    t5 = a1[2];
    t0 = a0[0];
    t1 = t0 & 0xFFFF;
    t1 = (t1 << 16) >> 16;
    RR_MD_MULT_U(t1, t3);
    RR_MD_LO(t1);
    t1 >>= 12;
    t1 &= 0xFFFF;
    t2 = t0 >> 16;
    RR_MD_MULT_U(t2, t4);
    RR_MD_LO(t2);
    t2 >>= 12;
    t2 <<= 16;
    t1 |= t2;
    a0[0] = t1;
    t0 = a0[1];
    t1 = t0 & 0xFFFF;
    t1 = (t1 << 16) >> 16;
    RR_MD_MULT_U(t1, t5);
    RR_MD_LO(t1);
    t1 >>= 12;
    t1 &= 0xFFFF;
    t2 = t0 >> 16;
    RR_MD_MULT_U(t2, t3);
    RR_MD_LO(t2);
    t2 >>= 12;
    t2 <<= 16;
    t1 |= t2;
    a0[1] = t1;
    t0 = a0[2];
    t1 = t0 & 0xFFFF;
    t1 = (t1 << 16) >> 16;
    RR_MD_MULT_U(t1, t4);
    RR_MD_LO(t1);
    t1 >>= 12;
    t1 &= 0xFFFF;
    t2 = t0 >> 16;
    RR_MD_MULT_U(t2, t5);
    RR_MD_LO(t2);
    t2 >>= 12;
    t2 <<= 16;
    t1 |= t2;
    a0[2] = t1;
    t0 = a0[3];
    t1 = t0 & 0xFFFF;
    t1 = (t1 << 16) >> 16;
    RR_MD_MULT_U(t1, t3);
    RR_MD_LO(t1);
    t1 >>= 12;
    t1 &= 0xFFFF;
    t2 = t0 >> 16;
    RR_MD_MULT_U(t2, t4);
    RR_MD_LO(t2);
    t2 >>= 12;
    t2 <<= 16;
    t1 |= t2;
    a0[3] = t1;
    t0 = a0[4];
    t1 = t0 & 0xFFFF;
    t1 = (t1 << 16) >> 16;
    RR_MD_MULT_U(t1, t5);
    RR_MD_LO(t1);
    t1 >>= 12;
    a0[4] = t1;
    return a0;
}
