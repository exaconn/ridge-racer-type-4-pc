#!/usr/bin/env python3
"""Crutch-debt tracker (modelled on parasite-pc tools/scripts/crutch_debt.py).
Counts matching crutches in src/main/PAL/*.c that must be removed to reach clean C.
usage: crutch_debt.py [--write-baseline] [--check]   (writes docs/CRUTCH_DEBT.md; --check fails if any category grew vs baseline)"""
import json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src/main/PAL"
BASE = ROOT / "tools/crutch_debt_baseline.json"
strip = lambda t: re.sub(r"//.*", "", re.sub(r"/\*.*?\*/", "", t, flags=re.S))
HW = "cfc2|ctc2|lwc2|swc2|mfc2|mtc2|nop"
PAT = {
    "pins": re.compile(r'register\s+[^;]*\basm\s*\(\s*"\$?\w+"\s*\)'),
    "barriers": re.compile(r'(?:__asm__|asm)\s*(?:volatile|__volatile__)?\s*\(\s*""'),
    "asm_bodies": re.compile(rf'\b(?:__asm__|asm)\s*(?:volatile|__volatile__)?\s*\(\s*"(?!\.|")(?!(?:{HW})\b)[a-z]'),
    "directives": re.compile(r'\b(?:__asm__|asm)\s*(?:volatile|__volatile__)?\s*\(\s*"\.'),
    "gte_asm": re.compile(rf'\b(?:__asm__|asm)\s*(?:volatile|__volatile__)?\s*\(\s*"(?:{HW})\b'),
    "gotos": re.compile(r"\bgoto\b"),
    "pad_arrays": re.compile(r"\b(?:int|char|short)\s+(?:pad\w*|new_var\w*)\s*\["),
    "raw_offset_derefs": re.compile(r"\*\s*\([^)]*\*\s*\)\s*\((?:[^();\n]|\([^();\n]*\))*?[+-]\s*(?:0x[0-9A-Fa-f]+|[1-9][0-9]*)"),
    "pointer_int_casts": re.compile(r"\(\s*(?:s32|u32|int|long|unsigned(?:\s+int)?)\s*\)\s*(?:[A-Za-z_&]|\()"),
    "gcc_2_7_2_units": re.compile(r"GCC_VERSION:\s*2\.7\.2"),
    "cc1_flags_units": re.compile(r"^/\* CC1_FLAGS:", re.M),
    "volatile_hacks": re.compile(r"\bvolatile\b"),
}
ORDER = list(PAT)
def collect():
    tot = {k: 0 for k in ORDER}; dirty = []
    for f in sorted(SRC.glob("*.c")):
        raw = f.read_text(); t = raw if False else strip(raw)
        row = {k: len(PAT[k].findall(raw if k in ("gcc_2_7_2_units", "cc1_flags_units") else t)) for k in ORDER}
        for k, v in row.items(): tot[k] += v
        if any(row[k] for k in ("pins", "barriers", "asm_bodies", "directives", "pad_arrays", "volatile_hacks", "gcc_2_7_2_units", "cc1_flags_units")): dirty.append(f.stem)
    return tot, dirty, len(list(SRC.glob("*.c")))
tot, dirty, n = collect()
md = ["# Crutch debt (auto-generated by tools/scripts/crutch_debt.py)\n", f"{n} C files, {len(dirty)} carry a matching crutch.\n", "| category | count |", "|---|---|"]
md += [f"| {k} | {tot[k]} |" for k in ORDER]
md += ["", "`gcc_2_7_2_units`/`cc1_flags_units` = compiler-selection markers (stock compilers, not hacks, but tracked). `gte_asm` = named GTE coprocessor ops (legit).", "Policy: pins/barriers must carry `/* ASM_BARRIER: reason */` (docs/BARRIERS.md); remove when stock compiler still matches without them."]
(ROOT / "docs/CRUTCH_DEBT.md").write_text("\n".join(md) + "\n")
for k in ORDER: print(f"{k:20} {tot[k]}")
print(f"{n} files, {len(dirty)} with crutches")
if "--write-baseline" in sys.argv: BASE.write_text(json.dumps(tot, indent=1)); print("baseline written")
if "--check" in sys.argv:
    b = json.loads(BASE.read_text()); bad = {k: (b[k], tot[k]) for k in ORDER if k in b and tot[k] > b[k] and k not in ("gotos", "gte_asm")}
    if bad: print("DEBT GREW:", bad); sys.exit(1)
