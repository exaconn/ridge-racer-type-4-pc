#!/usr/bin/env python3
"""Crutch-debt tracker (modelled on parasite-pc tools/scripts/crutch_debt.py).
Counts source-level cleanup indicators in resident and overlay C code.
Hardware operations, compiler selection, volatile and padding are not automatically defects.
usage: crutch_debt.py [--write-baseline] [--check]   (writes docs/CRUTCH_DEBT.md; --check fails if any category grew vs baseline)"""
import argparse, json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src/main/PAL"
BASE = ROOT / "tools/crutch_debt_baseline.json"
strip = lambda t: re.sub(r"//.*", "", re.sub(r"/\*.*?\*/", "", t, flags=re.S))
HW = "cfc2|ctc2|lwc2|swc2|mfc2|mtc2|nop"
PAT = {
    "pins": re.compile(r'\bregister\s+[^;]*?\b(?:__asm__|__asm|asm)\s*\(\s*"\$?\w+"\s*\)'),
    "barriers": re.compile(r'(?:__asm__|asm)\s*(?:volatile|__volatile__)?\s*\(\s*""'),
    "asm_bodies": re.compile(rf'\b(?:__asm__|asm)\s*(?:volatile|__volatile__)?\s*\(\s*"(?!\.|")(?!(?:{HW})\b)[a-z]'),
    "directives": re.compile(r'\b(?:__asm__|asm)\s*(?:volatile|__volatile__)?\s*\(\s*"\.'),
    "gte_asm": re.compile(rf'\b(?:__asm__|asm)\s*(?:volatile|__volatile__)?\s*\(\s*"(?:{HW})\b'),
    "gotos": re.compile(r"\bgoto\b"),
    "pad_arrays": re.compile(r"\b(?:int|char|short)\s+(?:pad\w*|new_var\w*)\s*\["),
    "raw_offset_derefs": re.compile(r"\*\s*\([^)]*\*\s*\)\s*\((?:[^();\n]|\([^();\n]*\))*?[+-]\s*(?:0x[0-9A-Fa-f]+|[1-9][0-9]*)"),
    "integer_casts": re.compile(r"\(\s*(?:s32|u32|int|long|uintptr_t|intptr_t|(?:unsigned|signed)(?:\s+(?:int|long))?)\s*\)\s*(?:[A-Za-z_&]|\()"),
    "gcc_2_7_2_units": re.compile(r"GCC_VERSION:\s*2\.7\.2"),
    "cc1_flags_units": re.compile(r"^/\* CC1_FLAGS:", re.M),
    "volatile_qualifiers": re.compile(r"\bvolatile\b"),
}
PAT.update({
    "legacy_type_blocks": re.compile(r"/\* legacy typing of shared globals in this part of the unit \*/"),
    "cast_alias_macros": re.compile(r"^\s*#define\s+\w+\s+\(\*\s*\(", re.M),
    "m2c_accesses": re.compile(r"\bM2C_(?:FIELD|ERROR|BITWISE|ROTATE)\w*\s*\("),
})
ORDER = list(PAT)
def collect(directory=SRC, overrides=None):
    """Count literal source occurrences, without expanding hardware/helper macros."""
    overrides = overrides or {}
    tot = {k: 0 for k in ORDER}
    affected = []
    files = sorted(Path(directory).rglob("*.c"))
    for f in files:
        raw = overrides.get(f, f.read_text())
        text = strip(raw)
        raw_categories = {"gcc_2_7_2_units", "cc1_flags_units", "legacy_type_blocks"}
        row = {k: len(PAT[k].findall(raw if k in raw_categories else text)) for k in ORDER}
        for k, value in row.items():
            tot[k] += value
        if any(row[k] for k in ("pins", "barriers", "asm_bodies", "directives",
                                "legacy_type_blocks", "cast_alias_macros", "m2c_accesses")):
            affected.append(str(f.relative_to(ROOT)))
    return tot, affected, len(files)


def snapshot(overrides=None):
    result = {}
    for name, directory in (("resident", SRC), ("overlays", ROOT/"src/overlays/PAL")):
        counts, affected, files = collect(directory, overrides)
        result[name] = dict(counts=counts, files=files, files_to_review=len(affected))
    return dict(schema_version=2, scopes=result)


def render(report):
    lines = ["# Source cleanup audit", "",
             "Generated by `tools/scripts/crutch_debt.py`. Counts are literal source occurrences;",
             "macros are not expanded. These are cleanup indicators, not matching metrics.", "",
             "| Category | Resident | Overlays |", "|---|---:|---:|"]
    for key in ORDER:
        lines.append(f"| {key} | {report['scopes']['resident']['counts'][key]} | "
                     f"{report['scopes']['overlays']['counts'][key]} |")
    for name, scope in report['scopes'].items():
        lines += ["", f"{name}: {scope['files']} C files; {scope['files_to_review']} files flagged for review."]
    lines += ["", "Register bindings include both `asm` and `__asm__`, with numeric or named registers.",
              "`gte_asm` is hardware access; compiler flags select stock toolchains. `volatile_qualifiers`,",
              "`pad_arrays` and `gotos` include legitimate code and must be reviewed in context.",
              "`integer_casts` includes scalar conversions as well as pointer conversions; it is not a pointer-safety count.",
              "The audit does not establish which constructs can be removed while preserving the match.",
              "", "Baseline schema 2 records both scopes with the corrected register detector.",
              "It is calibrated to the source before the first shared vehicle-rendering cleanup.",
              "Policy: see `docs/BARRIERS.md`; verify relocated instruction Levenshtein and the full EXE after cleanup."]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-baseline', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--json', action='store_true', help='Read-only JSON output; do not update documentation')
    args = parser.parse_args()
    report = snapshot()
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        (ROOT/"docs/CRUTCH_DEBT.md").write_text(render(report))
        print(render(report))
    if args.write_baseline:
        BASE.write_text(json.dumps(report, indent=2) + "\n")
    if args.check:
        baseline = json.loads(BASE.read_text())
        if baseline.get('schema_version') != report['schema_version']:
            raise SystemExit('Incompatible audit baseline; calibrate it with the corrected scanner.')
        bad = {}
        for name, scope in report['scopes'].items():
            previous = baseline['scopes'][name]['counts']
            for key, count in scope['counts'].items():
                if key not in ("gotos", "gte_asm") and count > previous[key]:
                    bad[f'{name}.{key}'] = (previous[key], count)
        if bad:
            print('CLEANUP INDICATORS GREW:', bad)
            raise SystemExit(1)


if __name__ == '__main__':
    main()
